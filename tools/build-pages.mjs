import { cp, mkdir, readdir, readFile, writeFile, stat, lstat, rm } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.resolve(root, 'dist');
const marker = path.join(output, '.beehave-build');
const maxFileSize = 25 * 1024 * 1024;

// Only remove our own generated directory, never source files or other project data.
if (output !== path.join(root, 'dist') || path.dirname(output) !== root) throw new Error('Invalid build output path.');
try {
  const info = await lstat(output);
  if (info.isSymbolicLink() || !info.isDirectory()) throw new Error('dist must be a regular directory.');
  const entries = await readdir(output);
  if (entries.length && !entries.includes('.beehave-build')) throw new Error('dist contains unmanaged files; choose another location before building.');
  await rm(output, { recursive: true });
} catch (error) { if (error.code !== 'ENOENT') throw error; }
await mkdir(output);
await writeFile(marker, 'Generated by tools/build-pages.mjs\n');

// Deploy only the desktop, the app, settings, and shared assets.
const inputs = ['index.html', 'index.js', 'preferences.js', 'ui.js', 'beehave.html', 'icon.png', 'manifest.json', 'calendar', 'settings', 'styles', 'media'];
for (const input of inputs) await cp(path.join(root, input), path.join(output, input), { recursive: true });

async function listFiles(directory) {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await listFiles(absolute));
    else files.push(absolute);
  }
  return files;
}
const files = await listFiles(output);
let totalBytes = 0;
let largest = { name: '', size: 0 };
for (const file of files) {
  const { size } = await stat(file);
  const name = path.relative(output, file);
  if (size > maxFileSize) throw new Error(`${name} exceeds Cloudflare Pages' 25 MiB file limit.`);
  if (/\.(jar|mcfunction|mca|zip)$/i.test(name)) throw new Error(`Non-website asset included: ${name}`);
  totalBytes += size;
  if (size > largest.size) largest = { name, size };
}
if (files.length > 20000) throw new Error('Website exceeds the Pages file count limit.');

async function validateReference(base, reference) {
  if (/^(?:[a-z]+:|\/\/|#)/i.test(reference)) return;
  const clean = reference.split(/[?#]/)[0];
  if (!clean) return;
  const target = path.resolve(path.dirname(base), clean);
  if (target !== output && !target.startsWith(output + path.sep)) throw new Error(`Reference leaves website output: ${reference}`);
  const info = await stat(target).catch(() => { throw new Error(`Missing website asset ${reference} in ${path.relative(output, base)}`); });
  if (info.isDirectory()) await stat(path.join(target, 'index.html'));
}
for (const file of files.filter(file => file.endsWith('.html'))) {
  const html = await readFile(file, 'utf8');
  for (const match of html.matchAll(/(?:src|href)="([^"]+)"/g)) await validateReference(file, match[1]);
}
const manifest = JSON.parse(await readFile(path.join(output, 'manifest.json'), 'utf8'));
for (const app of manifest.apps) {
  await validateReference(path.join(output, 'index.html'), app.path);
  await validateReference(path.join(output, 'index.html'), app.icon);
}
console.log(`Built ${files.length} website files in dist (${(totalBytes / 1024).toFixed(1)} KiB). Largest: ${largest.name} (${(largest.size / 1024).toFixed(1)} KiB).`);
